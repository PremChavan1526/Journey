package Autoboxing;

public class Demo {
    public static void main(String[] args) {
        
        int x = 10;
        Integer y =x; //autoboxing

        System.out.println(x);
        System.out.println(y);



        Integer a =20;
        int b = a;

        System.out.println(a);
        System.out.println(b);
    }
    
}
